# 1) თქვენი დავალებაა დაწეროთ ისეთი კოდი რომელშიც გაქვთ ორი მონაცემი: პირველი - რაიმე დიდი რიცხვი (მაგ. 123675312354) და მეორე რაიმე ერთი ციფრი (მაგ. 2), თქვენი დავალებაა დაითვალოთ რამდენჯერ გხვდებათ ეს მეორე პატარა რიცხვი დიდ რიცხვში. (ასევე დიდი რიცხვი არ გადააქციოთ სტრინგად, გამოიყენეთ სხვა გზა ამ ამოცანის ამოსახსნელად)

big_number = 123675312354
small_number = 2
count = 0

while big_number > 0:
    if big_number % 10 == small_number:
        count += 1
    big_number //= 10

print(count)

# 2) თქვენი დავალებაა დაწეროთ ისეთი კოდი, რომელშიც გაქვთ ერთი მონაცემი: რაიმე ნატურალური რიცხვი (მაგ. 360). თქვენი დავალებაა ეს რიცხვი დაშალოთ მარტივ მამრავლებად, ანუ იპოვოთ ისეთი მარტივი რიცხვები (რომლებიც მხოლოდ 1-ზე და საკუთარ თავზე იყოფა: 2, 3, 5, 7, 11...), რომელთა ერთმანეთზე გამრავლებითაც მიიღება თქვენი რიცხვი, და დაბეჭდოთ ისინი ზრდადობით. თუ რომელიმე მამრავლი რამდენჯერმე გვხვდება, იმდენჯერვე უნდა დაიბეჭდოს. (მაგ. 360-ისთვის პასუხია 2 2 2 3 3 5, რადგან 2 · 2 · 2 · 3 · 3 · 5 = 360).

