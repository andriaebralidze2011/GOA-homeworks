# 4) თქვენი დავალებაა დაწეროთ ისეთი კოდი, რომელშიც გაქვთ რიცხვების მასივი (მაგ. [4, 17, 2, 9, 31, 6]). თქვენი დავალებაა იპოვოთ ამ მასივში ყველაზე დიდი და ყველაზე პატარა რიცხვი და დაბეჭდოთ ისინი. (მაგ. ამ მასივისთვის პასუხია უდიდესი: 31, უმცირესი: 2). ასევე, არ გამოიყენოთ max(), min() და .sort(), მასივს ციკლით გადაუყევით და თავად შეადარეთ რიცხვები ერთმანეთს.

nums = [4, 17, 2, 9, 31, 6]

big = nums[0]
small = nums[0]

for i in nums:
    if i > big:
        big = i

    if i < small:
        small = i

print("biggest:", big)
print("smallest:", small) 
